export function getAllowableUsesForZone(zoneNameOrCategory) {
    if (!zoneNameOrCategory) return ALLOWABLE_USES_BY_ZONE;
    const query = zoneNameOrCategory.toLowerCase();
    
    const matched = ALLOWABLE_USES_BY_ZONE.filter(group => 
        group.zone.toLowerCase().includes(query) ||
        group.category.toLowerCase().includes(query)
    );

    return matched.length > 0 ? matched : ALLOWABLE_USES_BY_ZONE;
}
